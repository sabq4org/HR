CREATE TABLE IF NOT EXISTS employees (
  id TEXT PRIMARY KEY, employee_number TEXT NOT NULL UNIQUE, name TEXT NOT NULL, initials TEXT NOT NULL,
  title TEXT NOT NULL, department TEXT NOT NULL, email TEXT NOT NULL, location TEXT NOT NULL,
  manager_id TEXT REFERENCES employees(id), join_date TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('employee','manager','hr')),
  color TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active' CHECK(status='active')
);
CREATE TABLE IF NOT EXISTS leave_requests (
  id TEXT PRIMARY KEY, employee_id TEXT NOT NULL REFERENCES employees(id), start_date TEXT NOT NULL, end_date TEXT NOT NULL,
  days INTEGER NOT NULL CHECK(days > 0), note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL CHECK(status IN ('pending_manager','pending_hr','approved','rejected','cancelled')),
  version INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL, manager_decision_at TEXT, hr_decision_at TEXT, decision_reason TEXT
);
CREATE TABLE IF NOT EXISTS leave_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id TEXT NOT NULL REFERENCES employees(id), leave_id TEXT REFERENCES leave_requests(id),
  kind TEXT NOT NULL CHECK(kind IN ('allocation','reserve','release','consume')), days INTEGER NOT NULL CHECK(days != 0), created_at TEXT NOT NULL, actor_id TEXT
);
CREATE OR REPLACE FUNCTION prevent_append_only_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'append-only record'; END;
$$;
DROP TRIGGER IF EXISTS leave_ledger_no_update ON leave_ledger;
CREATE TRIGGER leave_ledger_no_update BEFORE UPDATE OR DELETE ON leave_ledger FOR EACH ROW EXECUTE FUNCTION prevent_append_only_mutation();
CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id TEXT NOT NULL, actor_role TEXT NOT NULL, action TEXT NOT NULL,
  resource_id TEXT NOT NULL, resource_version INTEGER, reason TEXT, created_at TEXT NOT NULL
);
DROP TRIGGER IF EXISTS audit_no_update ON audit_events;
CREATE TRIGGER audit_no_update BEFORE UPDATE OR DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION prevent_append_only_mutation();
CREATE TABLE IF NOT EXISTS idempotency (
  actor_id TEXT NOT NULL, action TEXT NOT NULL, key TEXT NOT NULL, payload_hash TEXT NOT NULL, response_json TEXT NOT NULL,
  PRIMARY KEY(actor_id, action, key)
);
CREATE TABLE IF NOT EXISTS outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_id TEXT NOT NULL REFERENCES employees(id), title TEXT NOT NULL,
  body TEXT NOT NULL, leave_id TEXT REFERENCES leave_requests(id), created_at TEXT NOT NULL, read_at TEXT
);
